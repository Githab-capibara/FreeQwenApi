#!/usr/bin/env node
/**
 * Build the OpenAPI document that the OWASP ZAP DAST scan consumes.
 *
 * The canonical contract lives in `openapi/openapi.yaml` and documents every
 * route, including the completion endpoints. Those endpoints forward the
 * request to the upstream Qwen service, which is not available in CI. When the
 * upstream is absent the application retries the failed upstream call several
 * times, so a single request takes seconds instead of milliseconds and an
 * active scan of the whole contract does not finish within the job budget.
 *
 * This script therefore derives a smaller document that contains only the
 * endpoints which answer deterministically without the upstream service. The
 * result is written to a temporary directory that is *not* tracked by Git, so
 * the contract stays single-sourced: `openapi/openapi.yaml` remains the only
 * place where the API surface is defined.
 *
 * Usage:
 *   node scripts/ci/build-dast-spec.js <output-file>
 *
 * Environment:
 *   DAST_PATH_REGEX   Regular expression of the paths to keep. Defaults to the
 *                     same deterministic set that the Schemathesis run uses.
 */

import fs from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';

const REPO_ROOT = path.resolve(import.meta.dirname, '..', '..');
const SOURCE_SPEC = path.join(REPO_ROOT, 'openapi', 'openapi.yaml');

const DEFAULT_PATH_REGEX = '^/(health|models|v1/models|status|)$';

const outputFile = process.argv[2];
if (!outputFile) {
    console.error('usage: node scripts/ci/build-dast-spec.js <output-file>');
    process.exit(1);
}

const pathRegex = new RegExp(process.env.DAST_PATH_REGEX ?? DEFAULT_PATH_REGEX);

const source = yaml.load(fs.readFileSync(SOURCE_SPEC, 'utf8'));
if (!source || typeof source !== 'object' || !source.paths) {
    console.error(`::error::${SOURCE_SPEC} does not contain an OpenAPI document`);
    process.exit(1);
}

const keptPaths = {};
for (const [route, operations] of Object.entries(source.paths)) {
    if (!pathRegex.test(route)) continue;
    keptPaths[route] = operations;
}

if (Object.keys(keptPaths).length === 0) {
    console.error(`::error::no path matched ${pathRegex}; the DAST scope would be empty`);
    process.exit(1);
}

const document = {
    ...source,
    info: {
        ...source.info,
        title: `${source.info?.title ?? 'API'} (DAST subset)`,
        description:
            'Generated by scripts/ci/build-dast-spec.js from openapi/openapi.yaml. '
            + 'It contains only the endpoints that answer deterministically without the upstream service.',
    },
    paths: keptPaths,
};

fs.mkdirSync(path.dirname(path.resolve(outputFile)), { recursive: true });
fs.writeFileSync(outputFile, yaml.dump(document, { lineWidth: 120, noRefs: true }), 'utf8');

console.log(`DAST scope: ${Object.keys(keptPaths).join(', ')}`);
console.log(`Wrote ${outputFile}`);
